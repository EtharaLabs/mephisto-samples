"""Author-side measurements, never difficulty evidence or a floor-setting search.

Determinism compares every generated byte across two generator invocations. Ladder
measurement scores static predictions through the actual submission reader and scorer.
All artifacts, temporary files and reports remain inside this standalone bundle.
"""
import argparse
import hashlib
import importlib.util
import json
import os
import subprocess
import sys
from pathlib import Path

import portfolio

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT / 'environment/workspace'
MEASUREMENTS = ROOT / 'solution/measurements'
spec = importlib.util.spec_from_file_location('desk_score', ROOT / 'tests/scoring/score.py')
assert spec is not None and spec.loader is not None
score = importlib.util.module_from_spec(spec)
spec.loader.exec_module(score)


def generated_bytes():
    files = [p for p in WORKSPACE.rglob('*') if p.is_file()]
    files += [ROOT / 'tests/hidden/truth.jsonl', MEASUREMENTS / 'generator_report.json']
    return {str(p.relative_to(ROOT)): p.read_bytes() for p in sorted(files)}


def determinism():
    runs = []
    for _ in range(2):
        result = subprocess.run([sys.executable, '-B', str(ROOT / 'solution/generate.py')], check=True,
                                capture_output=True, text=True, cwd=ROOT,
                                env=dict(os.environ, PYTHONDONTWRITEBYTECODE='1', OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1'))
        print(result.stdout, end='')
        runs.append(generated_bytes())
    differences = [p for p in sorted(set(runs[0]) | set(runs[1])) if runs[0].get(p) != runs[1].get(p)]
    report = {'byte_identical': not differences, 'different_paths': differences, 'files_compared': len(runs[0]),
              'sha256': {p: hashlib.sha256(b).hexdigest() for p, b in runs[0].items()}}
    (MEASUREMENTS / 'nonregression.json').write_text(json.dumps(report, indent=2) + '\n')
    assert not differences, differences
    print('BYTE DIFF:', len(differences), 'different files;', len(runs[0]), 'files compared')


def ladder():
    reports = {}
    for method in portfolio.METHODS:
        out = MEASUREMENTS / 'results' / method
        portfolio.write_rows(out / 'predictions.jsonl', portfolio.predict(WORKSPACE, method))
        reports[method] = score.evaluate_report(out, ROOT / 'tests/hidden/truth.jsonl')
        print(method, reports[method]['score'], [round(reports[method]['lanes'][n]['fraction'], 4) for n in score.LANES], flush=True)
    (MEASUREMENTS / 'ladder.json').write_text(json.dumps(reports, indent=2) + '\n')
    return reports


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('mode', choices=('determinism', 'ladder'))
    args = parser.parse_args()
    MEASUREMENTS.mkdir(parents=True, exist_ok=True)
    (determinism if args.mode == 'determinism' else ladder)()
