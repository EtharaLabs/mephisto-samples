"""Deterministic synthetic intercompany ledgers; no graded target is a random draw.

Run python -B solution/generate.py. Every generated byte is rooted at this bundle.
The private fitted desk in estimators.py converts public cases into review records.
"""
import hashlib
import json
import math
import random
from pathlib import Path

import estimators

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT / 'environment/workspace'
PUBLIC_KEY = 'transfer-pricing-settlement-public-v1-2026'
PAIR_COUNT = 360
HISTORY_PERIODS = (8, 10, 12)
QUERY_PERIODS = (16, 20)


def rng_for(label):
    return random.Random(int.from_bytes(hashlib.sha256((PUBLIC_KEY + '|' + label).encode()).digest(), 'big'))


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, sort_keys=True, indent=2, allow_nan=False) + '\n')


def outcome(rng, x, lane, period, band):
    """Noisy *published* closed-case processes, independent across operational views."""
    a, b, c, d, e, f = x
    shift = 0.12 * (period >= 14)
    noise = rng.gauss(0, 0.08)
    if lane == 0:
        return round(min(0.8, max(0.002, 0.05 + 0.20*a + 0.08*b + 0.08*a*b + 0.04*math.sin(4*c) + 0.08*d*d + shift + noise)), 6)
    if lane == 1:
        logits = [2*a, 2*b, 2*c, 2*d, 1.2*e, 2*e*f, 1.5*(1-f), 0.4 + band*0.3, 1.8*(1-f)+shift]
        mass = [math.exp(v + rng.gauss(0, 0.45)) for v in logits]
        total = sum(mass)
        return [round(v/total, 8) for v in mass[:8]]
    if lane == 2:
        z = -2.0 + 1.7*a + 1.8*b + 1.4*c - 2*d + 1.5*a*e + b*(1-d) + shift
        return int(rng.random() < 1 / (1 + math.exp(-z)))
    if lane == 3:
        z = 1.2 - 0.85*a - 0.55*b - 0.45*c + 1.25*d + 1.1*e - 0.3*f + 0.1*band + rng.gauss(0, 0.22)
        return min(3, max(0, int(math.floor(z + 0.5))))
    if lane == 4:
        return round(0.2 + 0.4*a + 0.3*b + 0.15*c + 0.3*d + 0.2*e + 0.3*math.sin(2*math.pi*f) + 0.2*a*d + shift + noise, 6)
    probability = 1 / (1 + math.exp(-(-1.5 + 1.2*a - 1.4*b + 1.8*c + d + 0.7*c*c + shift)))
    return round(math.exp(-2.5 + 0.6*a + 0.6*c + 0.7*d + rng.gauss(0, 0.35)), 6) if rng.random() < probability else 0.0


def generate_inputs():
    ids = [f'EP{i:04d}' for i in range(PAIR_COUNT)]
    queries = [dict(record_id=f'{a}:p{q}', pair_id=a, period=q) for q in QUERY_PERIODS for a in ids[80:]]
    estimators.write_rows(WORKSPACE / 'queries.jsonl', queries)
    for i, pair in enumerate(ids):
        write_json(WORKSPACE / 'register' / f'{pair}.json', {
            'pair_id': pair, 'provider_entity': f'LE{i:04d}', 'recipient_entity': f'LE{(i+37)%PAIR_COUNT:04d}',
            'provider_jurisdiction': ('DE','US','SG','GB')[i%4], 'recipient_jurisdiction': ('FR','JP','IN','NL')[(i//4)%4],
            'jurisdiction_band': i%4, 'functional_role': ('services','distribution','manufacturing','licensing')[i%4],
            'apa_reference': f'APA{i%23:03d}', 'currency': 'USD', 'cohort': 'group'})
    for lane, view in enumerate(estimators.VIEWS):
        for period in range(1, 21):
            rows = []
            for i in range(140):
                rng = rng_for(f'{view}|case|{period}|{i}')
                pair = rng.choice(ids)
                x = [rng.random() for _ in range(6)]
                y = outcome(rng, x, lane, period, int(pair[2:])%4)
                booked = min(20, period + rng.choice([0,0,0,1,2]))
                row = dict(zip(estimators.FIELDS[lane], x), pair_id=pair, kind='closed',
                           case_id=f'{view}:{period}:{i}', event_period=period,
                           booked_period=booked, outcome=y)
                if rng.random() < 0.28:
                    row['restated_period'] = booked + rng.randint(1, 6)
                    old = outcome(rng, x, lane, period-3, int(pair[2:])%4)
                    row['as_booked'] = {'outcome': old}
                rows.append(row)
            for pair in ids:
                rng = rng_for(f'{view}|snapshot|{period}|{pair}')
                base = rng_for(f'{view}|base|{pair}')
                x = [0.40*base.random() + 0.60*rng.random() for _ in range(6)]
                row = dict(zip(estimators.FIELDS[lane], x), pair_id=pair, period=period, kind='snapshot')
                if lane == 0:
                    row['charge_base'] = round(math.exp(rng.uniform(12.5, 15.0)), 2)
                if lane == 4:
                    row['settlement_base'] = round(math.exp(rng.uniform(11.5, 13.0)), 2)
                    row['paid_on_account'] = round(row['settlement_base'] * rng.uniform(0.3, 0.8), 2)
                if lane == 5:
                    row['tax_exposure'] = round(math.exp(rng.uniform(8.0, 10.0)), 2)
                rows.append(row)
            estimators.write_rows(WORKSPACE / view / f'{period}.jsonl', rows)
    write_json(WORKSPACE / 'dataset_metadata.json', {
        'public_generation_key': PUBLIC_KEY, 'currency': 'USD', 'period_unit': 'month',
        'periods': list(range(1,21)), 'history_periods': list(HISTORY_PERIODS), 'query_periods': list(QUERY_PERIODS),
        'allocation_keys': ['headcount','revenue','assets','transactions','floor_space','compute','licences','other'],
        'residual': 'cost base retained by the provider: shareholder or unsupported benefit costs',
        'method_tiers': ['CUP','cost plus','resale minus','profit split'],
        'cohort': 'all records published or requested in the same period',
        'features': {view: list(keys) for view, keys in zip(estimators.VIEWS, estimators.FIELDS)}})
    return ids, queries


def main():
    assert set(HISTORY_PERIODS + QUERY_PERIODS) == set(estimators.PERIODS)
    ids, queries = generate_inputs()
    historical = [dict(record_id=f'{a}:p{p}', pair_id=a, period=p) for p in HISTORY_PERIODS for a in ids]
    records = estimators.records_for(WORKSPACE, historical + queries)
    history = [dict(r, pair_id=q['pair_id'], period=q['period']) for r, q in zip(records, historical)]
    estimators.write_rows(WORKSPACE / 'history/review.jsonl', history)
    estimators.write_rows(ROOT / 'tests/hidden/truth.jsonl', records[len(historical):])
    write_json(ROOT / 'solution/measurements/generator_report.json', {
        'pairs': len(ids), 'legal_entities': len(ids), 'history_rows': len(history), 'graded_rows': len(queries),
        'periods': 20, 'seed': PUBLIC_KEY})
    print(json.dumps({'history_rows': len(history), 'graded_rows': len(queries)}))


if __name__ == '__main__':
    main()
