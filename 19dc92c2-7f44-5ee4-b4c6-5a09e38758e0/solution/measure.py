"""Author-side measurements, not evidence of a twelve-hour agent trajectory.

Re-run generator twice, compare every generated byte, freeze floors, measure the
analyst ladder, and exercise the separate scorer against oracle and empty outputs.
"""
import argparse
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tests' / 'scoring'))
from score import score_rows
from public_reference import METHODS, predictions, read_rows, write_rows


def fingerprint():
    paths = sorted((ROOT / 'environment' / 'workspace').rglob('*')) + sorted((ROOT / 'tests' / 'hidden').rglob('*'))
    return {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest() for p in paths if p.is_file()}


def regenerate():
    env = dict(os.environ, PYTHONDONTWRITEBYTECODE='1', OPENBLAS_NUM_THREADS='1', OMP_NUM_THREADS='1')
    subprocess.run([sys.executable, '-B', str(ROOT / 'solution' / 'generate.py')], check=True, cwd=ROOT, env=env)
    first = fingerprint()
    subprocess.run([sys.executable, '-B', str(ROOT / 'solution' / 'generate.py')], check=True, cwd=ROOT, env=env)
    second = fingerprint()
    differences = [p for p in sorted(first.keys() | second.keys()) if first.get(p) != second.get(p)]
    report = {'byte_identical': not differences, 'diff': differences, 'file_count': len(first), 'sha256': second}
    (ROOT / 'solution' / 'measurements' / 'nonregression.json').write_text(json.dumps(report, indent=2) + '\n')
    assert not differences, differences


def ladder():
    truth = read_rows(ROOT / 'tests' / 'hidden' / 'truth.jsonl')
    manifest = json.loads((ROOT / 'tests' / 'scoring' / 'scorer_manifest.json').read_text())
    workspace = ROOT / 'environment' / 'workspace'
    reports = {}
    for method in METHODS:
        path = ROOT / 'solution' / 'measurements' / 'results' / method / 'predictions.jsonl'
        rows = predictions(workspace, method)
        write_rows(path, rows)
        report = score_rows(rows, truth, manifest)
        report['prediction_sha256'] = hashlib.sha256(path.read_bytes()).hexdigest()
        reports[method] = report
        print(method, report['score'], flush=True)
    output = ROOT / 'solution' / 'measurements' / 'ladder.json'
    output.write_text(json.dumps(reports, indent=2) + '\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('phase', choices=['regenerate', 'ladder'])
    args = parser.parse_args()
    globals()[args.phase]()


if __name__ == '__main__':
    main()
